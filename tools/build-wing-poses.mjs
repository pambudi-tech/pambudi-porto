// Writes src/bird/wing-poses.mjs: every flap's cells (wing-motion.mjs),
// worked out here once instead of on each visitor's phone as the page
// starts. Each cell is two characters of CODE, x then y. Run after changing
// the bird's poses or how its wings move:
//
//     node tools/build-wing-poses.mjs
import { writeFileSync } from 'node:fs';
import { buildWingPoses } from '../src/bird/wing-motion.mjs';
import { WING_CODE } from '../src/bird/wing-code.mjs';

const poses = buildWingPoses().map(pose => pose.map(([x, y]) => WING_CODE[x] + WING_CODE[y]).join(''));
writeFileSync(new URL('../src/bird/wing-poses.mjs', import.meta.url), `// Generated by tools/build-wing-poses.mjs from wing-motion.mjs; do not edit.
import { decodeWingPoses } from './wing-code.mjs';

export const WING_POSES = decodeWingPoses([
${poses.map(pose => `  '${pose}',`).join('\n')}
]);
`);
