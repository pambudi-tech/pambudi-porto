// Writes src/preloader/title-art.mjs: the welcome's title, "Welcome to House
// of Pambudi", from its outlined master (source-images/welcome-title.svg),
// one path a letter so the ink seeds each letter on its own (ink-growth.mjs).
// Coordinates are kept as exported: rounded, a hairline's cusp drew apart.
// Run after replacing the master:
//
//     node tools/build-title-art.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(new URL('./source-images/welcome-title.svg', import.meta.url), 'utf8');
const viewBox = source.match(/viewBox="([^"]+)"/)[1];
const paths = [...source.matchAll(/<path d="([^"]+)"/g)].map(([, d]) => d);
writeFileSync(new URL('../src/preloader/title-art.mjs', import.meta.url), `// Generated by tools/build-title-art.mjs from welcome-title.svg; do not edit.
export const TITLE_VIEWBOX = '${viewBox}';
export const TITLE_LETTERS = [
${paths.map(d => `  '${d}',`).join('\n')}
];
`);
console.log(paths.length, 'letters');
